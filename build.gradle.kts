// Generate a tiny Kotlin file holding the build version so runtime code
// can read the plugin version without depending on PluginManagerCore
// (now @ApiStatus.Internal in 2026.2+ EAP — the marketplace verifier
// flags it). Regenerates on every compile so dev-timestamp suffixes
// reflect the actual build.
val generatedSrcDir = layout.buildDirectory.dir("generated/sources/buildInfo/kotlin/main")
val generateBuildInfo = tasks.register("generateBuildInfo") {
    val outDir = generatedSrcDir
    val versionString = project.version.toString()
    inputs.property("version", versionString)
    outputs.dir(outDir)
    doLast {
        val dir = outDir.get().asFile.resolve("com/claudecode")
        dir.mkdirs()
        dir.resolve("BuildInfo.kt").writeText(
            """
            // Generated by build.gradle.kts — do not edit. See generateBuildInfo.
            package com.claudecode

            internal object BuildInfo {
                const val VERSION: String = "$versionString"
            }
            """.trimIndent() + "\n"
        )
    }
}
kotlin {
    sourceSets["main"].kotlin.srcDir(generatedSrcDir)
}
tasks.named("compileKotlin") {
    dependsOn(generateBuildInfo)
}

